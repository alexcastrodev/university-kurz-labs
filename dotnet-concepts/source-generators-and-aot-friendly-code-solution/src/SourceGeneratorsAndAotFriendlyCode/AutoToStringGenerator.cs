using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace SourceGeneratorsAndAotFriendlyCode;

/// <summary>
/// What the generator needs to know about one marked class. It is a record of simple values on purpose:
/// value equality is what lets Roslyn see "nothing changed" and skip the output step.
/// Never put ISymbol, SyntaxNode or Location in a model.
/// </summary>
public sealed record ClassModel(string? Namespace, string Name, bool IsPartial, string Properties);

// NOTE: this lab targets net10.0 so the tests can reference the generator directly. A generator shipped
// as a real analyzer package must target netstandard2.0 and be referenced with OutputItemType="Analyzer".
[Generator]
public sealed class AutoToStringGenerator : IIncrementalGenerator
{
    public const string AttributeMetadataName = "Gen.AutoToStringAttribute";
    public const string ModelStepName = "Model";

    public const string AttributeSource = """
        namespace Gen
        {
            [System.AttributeUsage(System.AttributeTargets.Class)]
            internal sealed class AutoToStringAttribute : System.Attribute { }
        }
        """;

    public const string IgnoreAttributeMetadataName = "Gen.AutoToStringIgnoreAttribute";

    public const string IgnoreAttributeSource = """
        namespace Gen
        {
            [System.AttributeUsage(System.AttributeTargets.Property)]
            internal sealed class AutoToStringIgnoreAttribute : System.Attribute { }
        }
        """;

    public static readonly DiagnosticDescriptor NotPartial = new(
        id: "AUTOTS001",
        title: "Class must be partial",
        messageFormat: "Class '{0}' is marked with [AutoToString] and must be declared partial",
        category: "SourceGeneration",
        defaultSeverity: DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(AddAttribute);
        var models = BuildPipeline(context.SyntaxProvider);
        context.RegisterSourceOutput(models, Emit);
    }

    public static void AddAttribute(IncrementalGeneratorPostInitializationContext context)
    {
        context.AddSource("AutoToStringAttribute.g.cs", AttributeSource);
        context.AddSource("AutoToStringIgnoreAttribute.g.cs", IgnoreAttributeSource);
    }

    public static IncrementalValuesProvider<ClassModel> BuildPipeline(SyntaxValueProvider syntax)
    {
        return syntax
            .ForAttributeWithMetadataName(
                AttributeMetadataName,
                predicate: static (node, _) => node is ClassDeclarationSyntax,
                transform: static (ctx, _) => CreateModel(ctx))
            .WithTrackingName(ModelStepName);
    }

    public static ClassModel CreateModel(GeneratorAttributeSyntaxContext context)
    {
        var symbol = (INamedTypeSymbol)context.TargetSymbol;
        var isPartial = context.TargetNode is ClassDeclarationSyntax declaration
            && declaration.Modifiers.Any(SyntaxKind.PartialKeyword);
        var properties = symbol.GetMembers()
            .OfType<IPropertySymbol>()
            .Where(p => !p.IsStatic && !p.IsIndexer
                && p.DeclaredAccessibility == Accessibility.Public
                && p.GetMethod is not null
                && !p.GetAttributes().Any(a => a.AttributeClass?.ToDisplayString() == IgnoreAttributeMetadataName))
            .Select(p => p.Name);
        var ns = symbol.ContainingNamespace.IsGlobalNamespace ? null : symbol.ContainingNamespace.ToDisplayString();
        return new ClassModel(ns, symbol.Name, isPartial, string.Join(",", properties));
    }

    public static string Render(ClassModel model)
    {
        var names = model.Properties.Length == 0 ? [] : model.Properties.Split(',');
        var list = string.Join(", ", names.Select(name => $"{name}={{{name}}}"));
        var inner = list.Length == 0 ? " " : $" {list} ";
        var cls = $"partial class {model.Name}\n{{\n"
            + $"    public string ToDisplayString() => $\"{model.Name} {{{{{inner}}}}}\";\n}}\n";
        return model.Namespace is null
            ? $"// <auto-generated/>\n{cls}"
            : $"// <auto-generated/>\nnamespace {model.Namespace}\n{{\n{cls}}}\n";
    }

    public static void Emit(SourceProductionContext context, ClassModel model)
    {
        if (!model.IsPartial)
        {
            context.ReportDiagnostic(Diagnostic.Create(NotPartial, Location.None, model.Name));
            return;
        }

        context.AddSource($"{model.Name}.g.cs", Render(model));
    }
}
